#!/usr/bin/env python3
"""Export Android's theme tokens to Fixtures/golden/theme/theme-tokens.json (the parity contract for BoarCore's Theme).

Reads .ref/android-native/app/src/main/java/team/sopa/boar/ui/theme/{ThemeTokens,ExtraThemes}.kt:
the Campfire and Moonlight palettes, Paper (Moonlight copied with overrides), Spacing, Radii and TypeTokens.
The derived extras (Tactical Red, Hacker Green, ...) mix colors in Oklab: scripts/export-vault-themes.sh computes them
with Compose on the JVM into Fixtures/golden/theme/vault-themes.json, and this script copies them into the Swift file.

Usage: python3 scripts/export-theme-tokens.py   (refresh .ref first with scripts/sync-reference.sh)
       It also rewrites Sources/BoarCore/ThemePalettes.swift from the same data; ThemeTokensTests checks both agree.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEME = ROOT / ".ref/android-native/app/src/main/java/team/sopa/boar/ui/theme"
OUT = ROOT / "Fixtures/golden/theme/theme-tokens.json"
VAULT = ROOT / "Fixtures/golden/theme/vault-themes.json"
SWIFT = ROOT / "Sources/BoarCore/ThemePalettes.swift"

COLOR = re.compile(r"(\w+)\s*=\s*Color\(0x([0-9A-Fa-f]{8})\)")


def block(src: str, start: str) -> str:
    """The text from `start` to its matching closing parenthesis."""
    i = src.index(start)
    j = src.index("(", i)
    depth = 0
    for k in range(j, len(src)):
        if src[k] == "(":
            depth += 1
        elif src[k] == ")":
            depth -= 1
            if depth == 0:
                return src[j : k + 1]
    raise ValueError(start)


def palette(text: str) -> dict:
    colors = {name: "#" + hexv.upper() for name, hexv in COLOR.findall(text)}
    meta = dict(re.findall(r'\b(id|name|icon)\s*=\s*"([^"]*)"', text))
    light = re.search(r"\blight\s*=\s*true", text) is not None
    return {"meta": meta, "light": light, "colors": colors}


def ints(text: str) -> dict:
    return {k: int(v) for k, v in re.findall(r"const val (\w+) = (\d+)", text)}


def type_scale(text: str) -> dict:
    out = {}
    pat = re.compile(r'"([\w.]+)" to TextSpec\("([\w-]+)", ([\d.]+)f, (?:([\d.]+)f|null), (\d+), (?:(-?[\d.]+)f|null)\)')
    for name, family, size, line, weight, spacing in pat.findall(text):
        out[name] = {
            "family": family,
            "size": float(size),
            "lineHeight": float(line) if line else None,
            "weight": int(weight),
            "letterSpacing": float(spacing) if spacing else None,
        }
    return out


def main() -> int:
    tokens = (THEME / "ThemeTokens.kt").read_text()
    extras = (THEME / "ExtraThemes.kt").read_text()

    campfire = palette(block(tokens, "val campfire = BoarColors"))
    moonlight = palette(block(tokens, "val moonlight = BoarColors"))
    paper_over = palette(block(extras, "val paper = ThemeTokens.moonlight.copy"))
    paper = {
        "meta": paper_over["meta"],
        "light": paper_over["light"],
        "colors": {**moonlight["colors"], **paper_over["colors"]},
    }
    for p in (campfire, moonlight):
        assert len(p["colors"]) == 59, (p["meta"], len(p["colors"]))

    themes = []
    for p in (campfire, moonlight, paper):
        themes.append({**p["meta"], "light": p["light"], "colors": p["colors"]})

    spacing = ints(tokens.split("object Spacing")[1].split("}")[0])
    radii = ints(tokens.split("object Radii")[1].split("}")[0])
    type_src = tokens.split("object TypeTokens")[1]
    scales = {
        name: type_scale(type_src.split(f"val {name} = mapOf(")[1].split("\n    )")[0])
        for name in ("compact", "standard", "large")
    }
    default_id = re.search(r'DEFAULT_ID = "(\w+)"', tokens).group(1)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    data = {"defaultId": default_id, "themes": themes, "spacing": spacing, "radii": radii, "type": scales}
    OUT.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(themes)} themes, {sum(len(s) for s in scales.values())} text styles")
    # The Boar Avatars themes Android derives in Oklab, in Moonlight's token order (the initializer's).
    order = list(moonlight["colors"].keys())
    derived = []
    for t in json.loads(VAULT.read_text()):
        if t["id"] == "paper":
            assert {k: v for k, v in t["colors"].items()} == paper["colors"], "Paper differs from the JVM's"
            continue
        assert sorted(t["colors"]) == sorted(order), t["id"]
        derived.append({**t, "colors": {k: t["colors"][k] for k in order}})
    write_swift(themes + derived)
    print(f"wrote {SWIFT.relative_to(ROOT)}")
    return 0


def write_swift(themes: list) -> None:
    lines = [
        "// Generated by scripts/export-theme-tokens.py from Android's ThemeTokens.kt and ExtraThemes.kt (the Boar Avatars",
        "// themes through Fixtures/golden/theme/vault-themes.json). Don't edit by hand.",
        "",
        "extension BoarPalette {",
    ]
    for t in themes:
        name = re.sub(r"_(\w)", lambda m: m.group(1).upper(), t["id"])
        lines.append(f"    public static let {name} = BoarPalette(")
        lines.append(f"        id: \"{t['id']}\", name: \"{t['name']}\", icon: \"{t['icon']}\", light: {'true' if t['light'] else 'false'},")
        names = list(t["colors"].keys())
        for i, name in enumerate(names):
            hexv = t["colors"][name][1:]
            end = "," if i < len(names) - 1 else ""
            lines.append(f"        {name}: ARGB(0x{hexv}){end}")
        lines.append("    )")
        lines.append("")
    lines[-1] = "}"
    SWIFT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    sys.exit(main())
